-- در سطح هر Rule (نسخه ۴) — برای اصلاح "KW"/"kW"
-- ==========================================================================
-- چرا این Migration لازم شد:
-- برخی داده‌های واقعی محصولات واحد توان را به‌صورت "KW" (حروف بزرگ) ذخیره
-- کرده‌اند، در حالی که Rule فعلی فقط "kW" را دقیقاً (case-sensitive) تشخیص
-- می‌داد. طبق دستور، حل این مورد نباید با case-insensitive کردن کل موتور
-- Technical Formatter انجام شود (ریسک برخورد با کدهای مدل/SKU/نام
-- محصولات)، بلکه باید یک ویژگی قابل‌کنترل *در سطح خودِ Rule* باشد.
--
-- ستون جدید case_sensitive:
--   1 (پیش‌فرض، دقیقاً رفتار قبلی) → تطابق حساس به بزرگی/کوچکی حروف.
--   0                              → این Rule به‌طور خاص بدون‌حساسیت به
--                                     بزرگی/کوچکی حروف تطابق می‌یابد؛ فقط
--                                     همین یک Rule، نه کل سیستم.
--
-- چون خروجی نمایشی در هر دو حالت از display_value/match_value استاندارد
-- خودِ Rule خوانده می‌شود (نه از متن ورودی)، صرف‌نظر از این‌که ورودی واقعی
-- «KW»، «Kw»، «kw» یا «kW» باشد، خروجی همیشه دقیقاً «kW» است.
--
-- این تغییر به SQLite ALTER TABLE ADD COLUMN ساده نیاز دارد (بدون تغییر
-- CHECK constraint موجود روی rule_type)، پس نیازی به بازسازی کامل جدول
-- (مثل Migrationهای v2/v3) نیست؛ تمام Ruleهای موجود دقیقاً حفظ می‌شوند.
--
-- اجرا (فقط همین یک فایل جدید؛ Migrationهای قبلی technical-format-rules*
-- دوباره اجرا نشوند):
--   npx wrangler d1 execute tasisatapadana-db --remote --file=./database/technical-format-rules-v4.sql
-- ==========================================================================

ALTER TABLE technical_format_rules ADD COLUMN case_sensitive INTEGER NOT NULL DEFAULT 1;

-- فقط قانون واحد «kW» به‌طور خاص بدون‌حساسیت به بزرگی/کوچکی حروف می‌شود تا
-- «24KW»، «25.2KW»، «8.5KW»، «23.3KW»، «7.4KW» (و همچنان «24kW»/«24 kW»)
-- همگی به شکل استاندارد «24 kW» نمایش داده شوند. بقیه‌ی Ruleها (از جمله
-- واحدهای تک‌حرفی پرریسک مثل C و F) دست‌نخورده و حساس به بزرگی/کوچکی حروف
-- باقی می‌مانند.
UPDATE technical_format_rules SET case_sensitive = 0 WHERE rule_type = 'unit' AND match_value = 'kW';
